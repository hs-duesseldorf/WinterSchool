#!/usr/bin/env bash
# Builds the live mocap test setup (IK Rigs, retargeters, Live Link preset, /Game/Mocap/MocapLive), see setup_mocap.py.
#   Scripts/setup_mocap.sh     # Captury skeleton once a recording is imported (Scripts/retarget_anims.sh), else Manny
#   MOCAP_SOURCE=/Game/... MOCAP_SOURCE_NAME=Name Scripts/setup_mocap.sh  # any other streamed skeleton
# Close the editor first (it would hold the packages).
set -euo pipefail
source "$(dirname "$0")/config.sh"
if editor_open && [ -z "${FORCE:-}" ]; then
    echo "The editor has $(basename "$UPROJECT") open. Save and close it first (or FORCE=1)." >&2; exit 1
fi
# generated by the previous run: the map and preset are rebuilt from scratch (deleting them inside the editor leaves
# them in memory); the IK rigs and retargeters are kept (editor tweaks), REBUILD_RIGS=1 makes them again
if [ -n "${REBUILD_RIGS:-}" ]; then
    rm -rf "$ROOT/Content/Mocap/Rigs" "$ROOT/Content/Professor/IK_Professor.uasset" "$ROOT"/Content/Professor/RTG_*_To_Professor.uasset
fi
rm -rf "$ROOT/Content/Mocap/MocapLive.umap" "$ROOT/Content/Mocap/LLP_Captury.uasset" \
       "$ROOT/Content/__ExternalActors__/Mocap/MocapLive" "$ROOT/Content/__ExternalObjects__/Mocap/MocapLive"
export MOCAP_STATUS=$(mktemp)
mkdir -p "$ROOT/Scripts/logs"
"$ENGINE/Engine/Binaries/Linux/UnrealEditor" "$UPROJECT" -ExecutePythonScript="$ROOT/Scripts/setup_mocap.py" \
    -unattended -nosplash -NoSound -stdout > "$ROOT/Scripts/logs/setup_mocap.log" 2>&1 || true
cat "$MOCAP_STATUS"; grep -q '^OK' "$MOCAP_STATUS"
